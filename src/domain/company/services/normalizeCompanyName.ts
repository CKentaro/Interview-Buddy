/**
 * 企業名の表記ゆれを吸収するための正規化。
 *
 * 「株式会社トヨタ自動車」「トヨタ自動車(株)」「ＴＯＹＯＴＡ」のように、同じ企業でも
 * 入力のされ方は揺れる。検索キー（Company.searchKey）の生成と、求人ページから
 * 抽出した企業名の突き合わせは、どちらもこの 1 つの関数を通す。
 * 検索側とマッチ側で規則がずれると、候補に出るのに紐づかない、という不整合が起きる。
 *
 * Prisma も Next.js も import しない純粋な関数（シードスクリプトからも直接使う）。
 */

/** 取り除く法人格の表記。長いものから順に消す（「株式会社」より先に「(株)」を消さない）。 */
const LEGAL_ENTITY_FORMS = [
  "株式会社",
  "有限会社",
  "合同会社",
  "合名会社",
  "合資会社",
  "一般社団法人",
  "一般財団法人",
  "公益社団法人",
  "公益財団法人",
  "特定非営利活動法人",
  "独立行政法人",
  "国立大学法人",
  "医療法人社団",
  "医療法人",
  "学校法人",
  "社会福祉法人",
  "宗教法人",
  "協同組合",
  "(株)",
  "(有)",
  "(同)",
];

/**
 * 比較・検索に使う正規化名を返す。
 *
 * NFKC で全角英数と ㈱ 等の合字を開き、法人格・空白・記号を落として小文字に揃える。
 * 結果が空になる場合（「株式会社」だけ等）は空文字を返す。呼び出し側で弾くこと。
 */
export function normalizeCompanyName(raw: string): string {
  // NFKC は ㈱ → (株)、Ｔ → T、全角空白 → 半角空白 に開く。
  let value = raw.normalize("NFKC").toLowerCase();

  for (const form of LEGAL_ENTITY_FORMS) {
    value = value.split(form.toLowerCase()).join("");
  }

  // 空白・記号（・, ., -, &, 括弧など）は表記ゆれの原因にしかならないので落とす。
  // 日本語（漢字・かな）と英数字だけを残す。
  return value.replace(/[^\p{Letter}\p{Number}]/gu, "");
}
